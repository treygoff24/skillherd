#!/usr/bin/env bash
# Print the THIRD-PARTY-NOTICES file for the crates compiled into the `skillherd`
# binary on its supported targets (macOS and Linux, x86_64 and aarch64).
#
#   bash scripts/third-party-notices.sh > THIRD-PARTY-NOTICES
#
# The crate set is every normal (not dev, not build) dependency that
# `cargo tree` reports for any supported target, from skill/Cargo.lock. For
# each crate it prints the declared license, the repository, and every license
# file shipped in the published crate, verbatim; a text identical to one
# already printed is referred back to instead of repeated.
# Needs cargo and jq. The output depends only on Cargo.lock and the crate
# sources, so CI regenerates it and fails when the committed file differs.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
MANIFEST="$ROOT/skill/Cargo.toml"
TARGETS="aarch64-apple-darwin x86_64-apple-darwin aarch64-unknown-linux-gnu x86_64-unknown-linux-gnu"
export LC_ALL=C

WORK=$(mktemp -d "${TMPDIR:-/tmp}/third-party-notices.XXXXXX")
trap 'rm -rf "$WORK"' EXIT

sha256() {
  if command -v sha256sum > /dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  else
    shasum -a 256 "$1" | cut -d' ' -f1
  fi
}

cargo metadata --manifest-path "$MANIFEST" --format-version 1 --locked > "$WORK/metadata.json"

# "name version" for every normal dependency on any supported target.
for target in $TARGETS; do
  cargo tree --manifest-path "$MANIFEST" --locked -e normal --prefix none \
    --target "$target" --format '{p}'
done | awk '$1 != "skillherd" { sub(/^v/, "", $2); print $1, $2 }' | sort -u > "$WORK/crates.txt"

[ -s "$WORK/crates.txt" ] || { echo "no dependencies found" >&2; exit 1; }

cat <<'EOF'
THIRD-PARTY-NOTICES

The skillherd binary is built from the crates listed below. Each entry gives the
license its authors declared, the repository, and the license files shipped
in the published crate, verbatim. Where a crate offers a choice of licenses,
skillherd uses the crate under the MIT license if it is one of the choices.

Generated by scripts/third-party-notices.sh from skill/Cargo.lock.
Do not edit by hand.
EOF

: > "$WORK/seen.txt"
while read -r name version; do
  jq -r --arg n "$name" --arg v "$version" '
    .packages[] | select(.name == $n and .version == $v)
    | [(.license // "not declared"), (.repository // "not declared"), .manifest_path]
    | @tsv' "$WORK/metadata.json" > "$WORK/package.tsv"
  [ "$(wc -l < "$WORK/package.tsv")" -eq 1 ] \
    || { echo "expected exactly one package $name $version in cargo metadata" >&2; exit 1; }
  IFS=$'\t' read -r license repository manifest < "$WORK/package.tsv"
  dir=$(dirname "$manifest")

  printf '\n%s\n' '================================================================================'
  printf '%s %s\n' "$name" "$version"
  printf 'License: %s\n' "$license"
  printf 'Repository: %s\n' "$repository"

  found=0
  while IFS= read -r file; do
    found=1
    base=$(basename "$file")
    hash=$(sha256 "$file")
    first=$(awk -v h="$hash" '$1 == h { print $2, $3, $4; exit }' "$WORK/seen.txt")
    printf '\n--- %s ---\n' "$base"
    if [ -n "$first" ]; then
      printf '(Same text as %s above.)\n' "$first"
    else
      printf '%s %s %s %s\n' "$hash" "$name" "$version" "$base" >> "$WORK/seen.txt"
      cat "$file"
      # Keep entries separated even when a file lacks a final newline.
      [ -z "$(tail -c 1 "$file")" ] || printf '\n'
    fi
  done < <(find "$dir" -maxdepth 1 -type f \( -iname 'LICEN[CS]E*' -o -iname 'COPYING*' -o -iname 'UNLICENSE*' \) | sort)

  if [ "$found" -eq 0 ]; then
    printf '\nThis crate ships no license file; its declared license is %s.\n' "$license"
  fi
done < "$WORK/crates.txt"
