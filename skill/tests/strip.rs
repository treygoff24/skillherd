//! The Rust stripper against the Python one it replaced.
//!
//! `fixtures/strip/corpus.json` holds 328 documents — the old shell suite's
//! fixture files and seam cases, edge cases (CRLF, no final newline, Unicode,
//! stray and mismatched closes) and 300 seeded random documents built to hit
//! every branch of the grammar — with the output the Python
//! `bin/skill-render` `strip_bytes` produced for each of 2 platforms × 4
//! harness keys (`-`, `claude`, `codex`, `lane`): the stripped bytes and
//! whether markers were seen, or the error line and reason. The port must
//! reproduce every one of the 2,624 outputs exactly.

use serde_json::Value;

use skillherd::model::Platform;
use skillherd::strip::strip_bytes;

#[test]
fn linux_fences_and_legacy_cell_fences_have_the_same_selection() {
    for name in ["linux", "cell"] {
        let source =
            format!("before\n<!-- {name}-only -->\nlinux content\n<!-- /{name}-only -->\nafter\n");
        let linux = strip_bytes(source.as_bytes(), Platform::Linux, None).unwrap();
        assert!(
            linux.had_markers,
            "{name} must be a recognized machine fence"
        );
        assert_eq!(linux.bytes, b"before\nlinux content\nafter\n");
        let mac = strip_bytes(source.as_bytes(), Platform::Mac, None).unwrap();
        assert_eq!(mac.bytes, b"before\nafter\n");
    }
}

#[test]
fn the_port_reproduces_every_python_output_in_the_corpus() {
    let text = include_str!("fixtures/strip/corpus.json");
    let corpus: Value = serde_json::from_str(text).unwrap();
    let cases = corpus["cases"].as_array().unwrap();
    assert!(
        cases.len() >= 300,
        "the corpus is the oracle; it must not be empty"
    );

    let mut checked = 0;
    let mut fenced = 0;
    let mut errors = 0;
    let mut mismatches: Vec<String> = Vec::new();
    for case in cases {
        let name = case["name"].as_str().unwrap();
        let input = case["input"].as_str().unwrap().as_bytes();
        for (key, want) in case["outputs"].as_object().unwrap() {
            let (keep, harness) = key.split_once('/').unwrap();
            let keep = match keep {
                "mac" => Platform::Mac,
                "cell" => Platform::Linux,
                other => panic!("unknown platform {other}"),
            };
            let harness = (harness != "-").then_some(harness);
            let got = strip_bytes(input, keep, harness);
            checked += 1;
            match (&got, want.get("ok"), want.get("error")) {
                (Ok(stripped), Some(bytes), None) => {
                    fenced += usize::from(stripped.had_markers);
                    if stripped.bytes != bytes.as_str().unwrap().as_bytes()
                        || stripped.had_markers != want["had_markers"].as_bool().unwrap()
                    {
                        mismatches.push(format!(
                            "{name} {key}: got {:?} (markers {}), want {bytes} (markers {})",
                            String::from_utf8_lossy(&stripped.bytes),
                            stripped.had_markers,
                            want["had_markers"]
                        ));
                    }
                }
                (Err(error), None, Some(expected)) => {
                    errors += 1;
                    if error.line as u64 != expected["line"].as_u64().unwrap()
                        || error.reason != expected["reason"].as_str().unwrap()
                    {
                        mismatches.push(format!("{name} {key}: got {error}, want {expected}"));
                    }
                }
                _ => mismatches.push(format!("{name} {key}: got {got:?}, want {want}")),
            }
        }
    }
    assert!(
        mismatches.is_empty(),
        "{} of {checked} outputs differ from Python:\n{}",
        mismatches.len(),
        mismatches.join("\n")
    );
    assert!(
        checked >= 2600 && fenced > 500 && errors > 500,
        "{checked} {fenced} {errors}"
    );
}

/// `fixtures/strip/bytes/*.md` are raw-byte documents the JSON corpus cannot
/// hold (it carries text): byte-order marks before markers, text and `---`,
/// invalid UTF-8 and Latin-1 bytes, a non-ASCII marker name, NUL, form feed
/// and vertical tab, a no-break space, CR-only and CRLF line ends.
/// `expected.json` is what the Python `strip_bytes` returned for each (hex)
/// or raised, generated by `generate.py` there from the deleted script.
#[test]
fn the_port_reproduces_python_on_raw_byte_documents() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/strip/bytes");
    let expected: Value =
        serde_json::from_str(&std::fs::read_to_string(dir.join("expected.json")).unwrap()).unwrap();
    let cases = expected["cases"].as_object().unwrap();
    let mut inputs: Vec<String> = std::fs::read_dir(&dir)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .filter(|name| name.ends_with(".md"))
        .collect();
    inputs.sort();
    let mut listed: Vec<String> = cases.keys().cloned().collect();
    listed.sort();
    assert_eq!(
        inputs, listed,
        "every fixture has expectations and none is missing"
    );
    assert!(inputs.len() >= 10, "{inputs:?}");

    let mut mismatches = Vec::new();
    let mut checked = 0;
    for (name, outputs) in cases {
        let input = std::fs::read(dir.join(name)).unwrap();
        for (key, want) in outputs.as_object().unwrap() {
            let (keep, harness) = key.split_once('/').unwrap();
            let keep = match keep {
                "mac" => Platform::Mac,
                "cell" => Platform::Linux,
                other => panic!("unknown platform {other}"),
            };
            let harness = (harness != "-").then_some(harness);
            let got = strip_bytes(&input, keep, harness);
            checked += 1;
            let same = match (&got, want.get("ok_hex"), want.get("error")) {
                (Ok(stripped), Some(hex), None) => {
                    to_hex(&stripped.bytes) == hex.as_str().unwrap()
                        && stripped.had_markers == want["had_markers"].as_bool().unwrap()
                }
                (Err(error), None, Some(expected)) => {
                    error.line as u64 == expected["line"].as_u64().unwrap()
                        && error.reason == expected["reason"].as_str().unwrap()
                }
                _ => false,
            };
            if !same {
                mismatches.push(format!("{name} {key}: got {got:?}, want {want}"));
            }
        }
    }
    assert!(mismatches.is_empty(), "{}", mismatches.join("\n"));
    assert_eq!(checked, inputs.len() * 8);
}

fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

// ---- `skillherd strip`, the standalone command ------------------------------

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;

use tempfile::TempDir;

const FENCED: &str = "# fenced\n\nNEUTRAL-BEFORE line.\n\n<!-- mac-only -->\nMAC-ONLY-TEXT line.\n<!-- /mac-only -->\n\n  <!-- cell-only -->\nCELL-ONLY-TEXT line.\n  <!-- /cell-only -->\n\n<!-- claude-only -->\nCLAUDE-TEXT line.\n<!-- /claude-only -->\n\nNEUTRAL-AFTER line.\n";
const NESTED: &str = "# nested\n\n<!-- cell-only -->\none\n<!-- mac-only -->\ntwo\n<!-- /mac-only -->\n<!-- /cell-only -->\n";

fn strip_cmd(home: &Path, args: &[&str]) -> (i32, Value) {
    let output = assert_cmd::Command::cargo_bin("skillherd")
        .unwrap()
        .env_clear()
        .env("HOME", home)
        .env("PATH", std::env::var_os("PATH").unwrap_or_default())
        .arg("strip")
        .args(args)
        .output()
        .unwrap();
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    let envelope: Value = serde_json::from_str(stdout.trim())
        .or_else(|_| serde_json::from_str(stderr.trim()))
        .unwrap_or_else(|err| panic!("no envelope ({err}): stdout {stdout:?} stderr {stderr:?}"));
    (output.status.code().unwrap(), envelope)
}

/// A file with no marker comes back byte for byte; a fenced one keeps only
/// the blocks of the named machine, and every harness block without
/// `--harness`.
#[test]
fn strip_returns_the_text_a_surface_would_serve() {
    let home = TempDir::new().unwrap();
    let plain = home.path().join("plain.md");
    let fenced = home.path().join("fenced.md");
    let plain_text = "# plain\n\n\n\nMentions mac-only in prose.\n";
    fs::write(&plain, plain_text).unwrap();
    fs::write(&fenced, FENCED).unwrap();

    let (code, envelope) = strip_cmd(
        home.path(),
        &[
            "--keep",
            "mac",
            plain.to_str().unwrap(),
            fenced.to_str().unwrap(),
        ],
    );
    assert_eq!(code, 0, "{envelope}");
    let files = envelope["data"]["files"].as_array().unwrap();
    assert_eq!(files[0]["content"], plain_text);
    assert_eq!(files[0]["had_markers"], false);
    assert_eq!(
        files[1]["content"],
        "# fenced\n\nNEUTRAL-BEFORE line.\n\nMAC-ONLY-TEXT line.\n\nNEUTRAL-AFTER line.\n"
    );
    assert_eq!(files[1]["rewritten"], false);
    assert_eq!(
        fs::read_to_string(&fenced).unwrap(),
        FENCED,
        "read-only without -i"
    );
}

/// `-i` rewrites each file in place for the named machine and harness, keeps
/// its mode, and leaves no temporary file beside it.
#[test]
fn strip_in_place_rewrites_and_keeps_the_mode() {
    let home = TempDir::new().unwrap();
    let file = home.path().join("rules.md");
    fs::write(&file, FENCED).unwrap();
    fs::set_permissions(&file, fs::Permissions::from_mode(0o640)).unwrap();

    let (code, envelope) = strip_cmd(
        home.path(),
        &[
            "--keep",
            "cell",
            "--harness",
            "claude",
            "-i",
            file.to_str().unwrap(),
        ],
    );
    assert_eq!(code, 0, "{envelope}");
    assert_eq!(envelope["data"]["files"][0]["rewritten"], true);
    assert!(envelope["data"]["files"][0].get("content").is_none());
    assert_eq!(
        fs::read_to_string(&file).unwrap(),
        "# fenced\n\nNEUTRAL-BEFORE line.\n\nCELL-ONLY-TEXT line.\n\nCLAUDE-TEXT line.\n\nNEUTRAL-AFTER line.\n"
    );
    assert_eq!(
        fs::metadata(&file).unwrap().permissions().mode() & 0o7777,
        0o640
    );
    let names: Vec<String> = fs::read_dir(home.path())
        .unwrap()
        .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
        .collect();
    assert_eq!(names, ["rules.md"], "no temporary file is left behind");
}

/// A dry run of `-i` reports what would change and writes nothing.
#[test]
fn strip_in_place_dry_run_writes_nothing() {
    let home = TempDir::new().unwrap();
    let file = home.path().join("rules.md");
    fs::write(&file, FENCED).unwrap();
    let (code, envelope) = strip_cmd(
        home.path(),
        &["--keep", "mac", "-i", "--dry-run", file.to_str().unwrap()],
    );
    assert_eq!(code, 0, "{envelope}");
    assert_eq!(envelope["data"]["files"][0]["rewritten"], true);
    assert_eq!(fs::read_to_string(&file).unwrap(), FENCED);
}

/// `-i` never writes through a symlink: the link is refused and both it and
/// the file it points at are left as they were.
#[test]
fn strip_in_place_refuses_a_symlink() {
    let home = TempDir::new().unwrap();
    let target = home.path().join("target.md");
    let link = home.path().join("link.md");
    fs::write(&target, FENCED).unwrap();
    std::os::unix::fs::symlink(&target, &link).unwrap();

    let (code, envelope) = strip_cmd(
        home.path(),
        &["--keep", "mac", "-i", link.to_str().unwrap()],
    );
    assert_eq!(code, 2, "{envelope}");
    assert_eq!(envelope["error"]["code"], "usage");
    assert!(
        envelope["error"]["message"]
            .as_str()
            .unwrap()
            .contains("is a symlink"),
        "{envelope}"
    );
    assert_eq!(fs::read_to_string(&target).unwrap(), FENCED);
    assert!(
        fs::symlink_metadata(&link)
            .unwrap()
            .file_type()
            .is_symlink()
    );
}

/// One malformed file fails the whole run, 65, with nothing rewritten: the
/// good file named before it keeps every byte.
#[test]
fn a_malformed_file_fails_strip_and_writes_nothing() {
    let home = TempDir::new().unwrap();
    let good = home.path().join("good.md");
    let bad = home.path().join("bad.md");
    fs::write(&good, FENCED).unwrap();
    fs::write(&bad, NESTED).unwrap();

    let (code, envelope) = strip_cmd(
        home.path(),
        &[
            "--keep",
            "mac",
            "-i",
            good.to_str().unwrap(),
            bad.to_str().unwrap(),
        ],
    );
    assert_eq!(code, 65, "{envelope}");
    assert_eq!(envelope["error"]["code"], "render_failed");
    let message = envelope["error"]["details"]["errors"][0]["message"]
        .as_str()
        .unwrap();
    assert!(
        message.ends_with("line 5: <!-- mac-only --> opened while <!-- cell-only --> block from line 3 is still open (nesting is not allowed)"),
        "{message}"
    );
    assert_eq!(
        fs::read_to_string(&good).unwrap(),
        FENCED,
        "nothing was written"
    );
    assert_eq!(fs::read_to_string(&bad).unwrap(), NESTED);
}

/// `--harness` is a closed set: an unknown name is a usage error, not "no
/// harness".
#[test]
fn strip_refuses_an_unknown_harness() {
    let home = TempDir::new().unwrap();
    let file = home.path().join("rules.md");
    fs::write(&file, FENCED).unwrap();
    let (code, envelope) = strip_cmd(
        home.path(),
        &[
            "--keep",
            "mac",
            "--harness",
            "gemini",
            file.to_str().unwrap(),
        ],
    );
    assert_eq!(code, 2, "{envelope}");
    assert_eq!(envelope["error"]["code"], "usage");
}
